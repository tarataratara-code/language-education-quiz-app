let state = loadProgress();
let overrides = loadOverrides();
let active = [];
let index = 0;
let answered = false;
let currentView = "practice";

const $ = (id) => document.getElementById(id);

function loadProgress() {
  try {
    return JSON.parse(localStorage.getItem(STORAGE_KEY)) || {};
  } catch {
    return {};
  }
}

function saveProgress() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function loadOverrides() {
  try {
    return JSON.parse(localStorage.getItem(OVERRIDE_KEY)) || {};
  } catch {
    return {};
  }
}

function saveOverrides() {
  localStorage.setItem(OVERRIDE_KEY, JSON.stringify(overrides));
}

function answerOf(question) {
  return Number.isInteger(overrides[question.id]) ? overrides[question.id] : question.answer;
}

function isCorrectForProgress(record) {
  return record?.lastCorrect === true || Number(record?.correctCount) > 0;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function init() {
  renderRoundOptions();

  $("roundFilter").addEventListener("change", rebuild);
  $("modeFilter").addEventListener("change", rebuild);
  $("summaryFilter").addEventListener("change", renderSummary);
  $("practiceTab").addEventListener("click", () => setView("practice"));
  $("summaryTab").addEventListener("click", () => setView("summary"));
  $("startFilteredPractice").addEventListener("click", startFilteredPractice);
  $("mistakePracticeButton").addEventListener("click", startMistakePractice);
  $("exportProgress").addEventListener("click", exportProgress);
  $("importProgress").addEventListener("click", importProgress);
  $("shuffleButton").addEventListener("click", () => {
    if (!active.length) return;
    active.sort(() => Math.random() - 0.5);
    index = 0;
    render();
  });
  $("answerButton").addEventListener("click", checkAnswer);
  $("nextButton").addEventListener("click", next);
  $("markSelectedCorrect").addEventListener("click", markSelectedCorrect);
  $("resetProgress").addEventListener("click", () => {
    if (!confirm("学習履歴をリセットしますか？")) return;
    state = {};
    saveProgress();
    rebuild();
  });

  rebuild();
  renderSummary();
}

function renderRoundOptions() {
  const roundFilter = $("roundFilter");
  const selected = roundFilter.value || "all";
  const rounds = [...new Set(QUESTIONS.map((question) => question.round))];
  const options = rounds.map((round) => {
    const questions = QUESTIONS.filter((question) => question.round === round);
    const correct = questions.filter((question) => isCorrectForProgress(state[question.id])).length;
    const status = correct === questions.length
      ? "✓ 完了"
      : correct > 0
        ? `◐ 途中 ${correct}/${questions.length}`
        : "○ 未着手";
    return `<option value="${round}">${status}｜${ROUND_LABELS[round] || `第${round}回`}</option>`;
  });
  roundFilter.innerHTML = `<option value="all">全教材（${QUESTIONS.length}問）</option>${options.join("")}`;
  roundFilter.value = rounds.some((round) => String(round) === selected) ? selected : "all";
}

function rebuild() {
  const round = $("roundFilter").value;
  const mode = $("modeFilter").value;
  active = QUESTIONS.filter((question) => {
    const record = state[question.id];
    if (round !== "all" && Number(round) !== question.round) return false;
    if (mode === "mistakes") return record?.lastCorrect === false;
    if (mode === "uncertain") return record?.uncertain === true;
    if (mode === "unmastered") return !record?.mastered;
    return true;
  });
  index = 0;
  render();
  renderSummary();
}

function render() {
  answered = false;
  const question = active[index];
  if (!question) {
    $("positionLabel").textContent = "0 / 0";
    $("progressBar").style.width = "0%";
    $("questionMeta").textContent = "対象の問題はありません";
    $("questionTitle").textContent = "今は復習対象がありません";
    $("questionText").textContent = "間違いだけモードで問題が表示されない場合は、まだ間違えた問題がない状態です。全問モードで1周してから戻ってきましょう。";
    $("choices").innerHTML = "";
    $("uncertainCheck").checked = false;
    $("resultPanel").hidden = true;
    $("answerButton").disabled = true;
    $("nextButton").disabled = true;
    updateDashboard();
    return;
  }
  $("positionLabel").textContent = `${index + 1} / ${active.length}`;
  $("progressBar").style.width = `${((index + 1) / active.length) * 100}%`;
  $("questionMeta").textContent = `${questionGroupLabel(question)} Q${question.no}`;
  $("questionTitle").textContent = `Q${question.no}`;
  $("questionText").textContent = question.text;
  $("choices").innerHTML = question.choices
    .map(
      (choice, choiceIndex) => `
        <label class="choice">
          <input type="radio" name="choice" value="${choiceIndex}" />
          <span>${choice}</span>
        </label>
      `,
    )
    .join("");
  $("uncertainCheck").checked = false;
  $("resultPanel").hidden = true;
  $("answerButton").disabled = false;
  $("nextButton").disabled = true;
  updateDashboard();
}

function selectedChoice() {
  const selected = document.querySelector('input[name="choice"]:checked');
  return selected ? Number(selected.value) : null;
}

function checkAnswer() {
  const question = active[index];
  const selected = selectedChoice();
  if (selected === null) {
    alert("選択肢を選んでください。");
    return;
  }

  const correct = selected === answerOf(question);
  const uncertain = $("uncertainCheck").checked;
  const prev = state[question.id] || { attempts: 0, correctCount: 0 };
  state[question.id] = {
    attempts: prev.attempts + 1,
    correctCount: prev.correctCount + (correct ? 1 : 0),
    lastCorrect: correct,
    uncertain,
    mastered: correct && !uncertain,
    lastSelected: selected,
    updatedAt: new Date().toISOString(),
  };
  saveProgress();

  showResult(question, correct);
  updateDashboard();
}

function showResult(question, correct) {
  $("resultPanel").hidden = false;
  $("resultBadge").className = `result-badge ${correct ? "good" : "bad"}`;
  $("resultBadge").textContent = correct ? "正解" : "もう一度";
  const answerLabel = question.round >= 101
    ? "TCJで確認した正答"
    : question.round <= 10
      ? "推定正答"
      : "解答集で確認した正答";
  $("answerLine").textContent = `${answerLabel}: ${question.choices[answerOf(question)]}`;
  const explanationLabel = question.round >= 101
    ? "TCJの解説"
    : question.round <= 10
      ? "補足解説"
      : "解説（解答集に基づく）";
  $("explanation").textContent = `問題ID: ${question.id} / ${explanationLabel}: ${question.explanation}`;
  const source = answerSourceOf(question);
  const sourceLink = $("answerSourceLink");
  if (source) {
    sourceLink.hidden = false;
    sourceLink.href = `./resources/${source.file}#page=${source.page}`;
    sourceLink.textContent = `${source.label}を開く`;
  } else {
    sourceLink.hidden = true;
    sourceLink.removeAttribute("href");
  }
  renderDiagram(question);
  $("answerButton").disabled = true;
  $("nextButton").disabled = false;
}

function renderDiagram(question) {
  if (question.round >= 101) {
    $("diagramPanel").hidden = true;
    $("diagramPanel").innerHTML = "";
    return;
  }

  const diagramId = QUESTION_DIAGRAMS[question.id];
  const diagram = diagramId ? DIAGRAMS[diagramId] : null;
  const panel = $("diagramPanel");
  if (!diagram) {
    panel.hidden = true;
    panel.innerHTML = "";
    return;
  }
  panel.hidden = false;
  panel.innerHTML = `<h3>図解: ${diagram.title}</h3><div class="diagram-grid">${diagram.html}</div>`;
}

function markSelectedCorrect() {
  const question = active[index];
  const selected = selectedChoice();
  if (selected === null) return;
  overrides[question.id] = selected;
  saveOverrides();
  const record = state[question.id];
  if (record && record.lastSelected === selected) {
    state[question.id] = {
      ...record,
      correctCount: record.correctCount + (record.lastCorrect ? 0 : 1),
      lastCorrect: true,
      mastered: !record.uncertain,
      updatedAt: new Date().toISOString(),
    };
    saveProgress();
  }
  showResult(question, true);
  updateDashboard();
  alert("この問題の正答を修正しました。");
}

function next() {
  if (!active.length) return;
  index = (index + 1) % active.length;
  render();
}

function updateDashboard() {
  const selectedRound = $("roundFilter").value;
  const dashboardQuestions = selectedRound === "all"
    ? QUESTIONS
    : QUESTIONS.filter((question) => question.round === Number(selectedRound));
  const records = dashboardQuestions.map((question) => state[question.id]).filter(Boolean);
  const attempts = records.reduce((sum, record) => sum + record.attempts, 0);
  const correct = records.reduce((sum, record) => sum + record.correctCount, 0);
  const correctQuestions = dashboardQuestions.filter((question) => isCorrectForProgress(state[question.id])).length;
  const remaining = dashboardQuestions.length - correctQuestions;
  $("overallRate").textContent = `${correctQuestions}/${dashboardQuestions.length}`;
  $("attemptRate").textContent = attempts ? `${Math.round((correct / attempts) * 100)}%` : "0%";
  $("remainingCount").textContent = `${remaining}問`;
  $("streakCount").textContent = String(currentStreak());

  const weak = QUESTIONS.filter((question) => {
    const record = state[question.id];
    return record && (!record.lastCorrect || record.uncertain);
  }).slice(-8);
  $("weakList").innerHTML = weak.length
    ? weak.map((question) => `<li>${questionGroupLabel(question)} Q${question.no}: ${question.text.slice(0, 42)}...</li>`).join("")
    : "<li>まだ弱点はありません。まず1周してみましょう。</li>";
  renderRoundOptions();
}

async function exportProgress() {
  const payload = JSON.stringify({
    app: "language-education-quiz-app",
    version: 1,
    exportedAt: new Date().toISOString(),
    state,
    overrides,
  });

  try {
    await navigator.clipboard.writeText(payload);
    alert("学習履歴をコピーしました。スマホ側で「履歴読み込み」に貼り付けると反映できます。");
  } catch {
    prompt("この学習履歴をコピーしてください。", payload);
  }
}

function importProgress() {
  const payload = prompt("コピーした学習履歴を貼り付けてください。");
  if (!payload) return;

  try {
    const imported = JSON.parse(payload);
    if (imported.app !== "language-education-quiz-app" || !imported.state) {
      throw new Error("Invalid progress data");
    }
    state = imported.state || {};
    overrides = imported.overrides || {};
    saveProgress();
    saveOverrides();
    rebuild();
    alert("学習履歴を読み込みました。");
  } catch {
    alert("読み込みできませんでした。コピーした文字列が途中で切れていないか確認してください。");
  }
}

function setView(view) {
  currentView = view;
  $("practiceView").hidden = view !== "practice";
  $("summaryView").hidden = view !== "summary";
  $("practiceTab").classList.toggle("active", view === "practice");
  $("summaryTab").classList.toggle("active", view === "summary");
  if (view === "summary") renderSummary();
}

function questionsBySummaryFilter() {
  const filter = $("summaryFilter").value;
  return QUESTIONS.filter((question) => {
    const record = state[question.id];
    if (filter === "mistakes") return record?.lastCorrect === false;
    if (filter === "uncertain") return record?.uncertain === true;
    if (filter === "unmastered") return !record?.mastered;
    return true;
  });
}

function renderSummary() {
  const questions = questionsBySummaryFilter();
  $("summaryCount").textContent = `${questions.length}問`;
  $("summaryList").innerHTML = questions.length
    ? `<div class="summary-list">${questions.map(summaryCard).join("")}</div>`
    : `<p class="empty-message">この条件に当てはまる問題はありません。練習で解くと、間違えた問題がここに集まります。</p>`;
}

function summaryCard(question) {
  const record = state[question.id];
  const status = summaryStatus(record);
  const className = record?.lastCorrect === false ? " mistake" : record?.mastered ? " mastered" : "";
  const selected = Number.isInteger(record?.lastSelected) ? question.choices[record.lastSelected] : "未回答";
  const source = answerSourceOf(question);
  const sourceHtml = source
    ? `<p class="summary-explanation"><a href="./resources/${source.file}#page=${source.page}" target="_blank">${escapeHtml(source.label)}を開く</a></p>`
    : "";
  return `
    <article class="summary-card${className}">
      <div class="summary-meta">
        <span>${questionGroupLabel(question)} Q${question.no} / ID: ${question.id}</span>
        <span class="status-pill ${status.className}">${status.label}</span>
      </div>
      <p class="summary-question">${escapeHtml(question.text)}</p>
      <p class="summary-answer"><strong>答え:</strong> ${escapeHtml(question.choices[answerOf(question)])}</p>
      <p class="summary-answer"><strong>前回の選択:</strong> ${escapeHtml(selected)}</p>
      <p class="summary-explanation"><strong>解説:</strong> ${escapeHtml(question.explanation)}</p>
      ${sourceHtml}
    </article>
  `;
}

function summaryStatus(record) {
  if (!record) return { label: "未回答", className: "" };
  if (record.lastCorrect === false) return { label: "間違い", className: "bad" };
  if (record.mastered) return { label: "マスター", className: "good" };
  if (record.uncertain) return { label: "自信なし", className: "bad" };
  return { label: "回答済み", className: "good" };
}

function startFilteredPractice() {
  const filter = $("summaryFilter").value;
  $("modeFilter").value = filter;
  setView("practice");
  rebuild();
}

function startMistakePractice() {
  const hasMistake = QUESTIONS.some((question) => state[question.id]?.lastCorrect === false);
  $("modeFilter").value = "mistakes";
  setView("practice");
  rebuild();
  if (!hasMistake) alert("今は間違えた問題がありません。まず全問モードで解いてみましょう。");
}

function currentStreak() {
  const answeredQuestions = Object.entries(state)
    .sort((a, b) => new Date(a[1].updatedAt) - new Date(b[1].updatedAt))
    .map(([, record]) => record);
  let streak = 0;
  for (let i = answeredQuestions.length - 1; i >= 0; i -= 1) {
    if (answeredQuestions[i].lastCorrect && !answeredQuestions[i].uncertain) streak += 1;
    else break;
  }
  return streak;
}

function registerServiceWorker() {
  if (!("serviceWorker" in navigator)) return;
  if (location.protocol === "file:") return;

  navigator.serviceWorker.register("./sw.js?v=20260710-9").catch(() => {
    // The app still works normally if the browser blocks PWA caching.
  });
}

init();
registerServiceWorker();
